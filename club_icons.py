def _check():
    """Every icon is 16 x 16 and uses only palette letters."""
    for name, rows in ICONS.items():
        assert len(rows) == 16, (name, len(rows))
        for row in rows:
            assert len(row) == 16, (name, row)
            assert set(row) <= set(PALETTE) | {"."}, (name, row)
        for word in ("card", "dock", "pill", "score", "shared", "waiting", "ship"):
            assert word not in name, name


_check()


def symbol(name):
    """One icon as an SVG <symbol>: one <path> per colour, one run per row."""
    rows = ICONS[name]
    paths = []
    for letter, colour in PALETTE.items():
        runs = []
        for y, row in enumerate(rows):
            x = 0
            while x < 16:
                if row[x] != letter:
                    x += 1
                    continue
                start = x
                while x < 16 and row[x] == letter:
                    x += 1
                runs.append("M%d %dh%dv1h-%dz" % (start, y, x - start, x - start))
        if runs:
            paths.append('<path fill="%s" d="%s"/>' % (colour, "".join(runs)))
    return '<symbol id="club-%s" viewBox="0 0 16 16">%s</symbol>' % (name, "".join(paths))


def sprite_file():
    """The whole set as one SVG file. The app serves it at /club-icons.svg,
    cached, and pages point into it: <use href="/club-icons.svg?v=..#club-chess">."""
    return ('<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">'
            + "".join(symbol(name) for name in ICONS) + "</svg>")
